"""Lectures 11.3 and 11.5: online evals. Score production traces, watch for drift, and feed a human review queue.

    traces = load_traces()                         # data/prod/traces.jsonl (synthetic production log)
    picked = sample(traces, rate=0.2)              # deterministic, by hashing the trace id
    scored = [score_trace(t) for t in picked]      # reference-free checks: no golden label exists for live traffic
    psi(counts_a, counts_b)                        # population stability index between two distributions

Offline evals have labels; production traffic doesn't. So online checks are the ones that need no expected
answer, only the trace itself: what the system of record said (the get_flight_status result recorded in the
trace), what the handler proposed, and what it sent. Three checks:
- confirmed:   every message sent is supported by the recorded lookup (status, new time, gate);
- trajectory:  a lookup before every write, and no write repeated for the same target;
- assertions:  Section 10's message assertions (facts, promises, internal codes), against the recorded record.
The judge from Section 10 isn't counted here either (its own kappa is below the bar); people review a sample
instead, and their verdicts become the labels the judge needs (review_queue).

About the data: data/prod/traces.jsonl is SYNTHETIC (every record has "synthetic": true), generated by
labs/s11/build_prod_log.py with a fixed seed. Its failure rates are parameters of that script, not
measurements of a model. The checks, the sampling, the tests and the drift numbers are real code.
"""
from __future__ import annotations

import hashlib
import json
import math
import re
from collections import Counter
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from ..settings import ROOT
from ..sim.flights import FlightRecord
from .checks import CheckResult, flight_key, message_assertions, write_target
from .dataset import WRITE_TOOLS

TRACES = ROOT / "data/prod/traces.jsonl"
CHECKS = ("confirmed", "trajectory", "assertions")
CLASSES = ("pass",) + CHECKS          # a trace's outcome class: "pass", or the first check it fails
SALT = "skyops-online-v1"


def load_traces(path: Path = TRACES) -> list[dict[str, Any]]:
    return [json.loads(l) for l in Path(path).read_text(encoding="utf-8").splitlines() if l.strip()]


def in_sample(trace_id: str, rate: float, salt: str = SALT) -> bool:
    """Hash sampling: the same trace is always in or out, on every machine and every rerun, and the decision
    doesn't depend on anything the handler did (sampling on outcomes would bias every rate you compute)."""
    h = int(hashlib.sha256(f"{salt}:{trace_id}".encode()).hexdigest()[:8], 16)
    return h / 0x100000000 < rate


def sample(traces: list[dict[str, Any]], rate: float, salt: str = SALT) -> list[dict[str, Any]]:
    return [t for t in traces if in_sample(t["trace_id"], rate, salt)]


def _record(result: dict[str, Any]) -> FlightRecord | None:
    try:
        return FlightRecord(**{k: result[k] for k in FlightRecord.__dataclass_fields__})
    except (KeyError, TypeError):
        return None


@dataclass
class Scored:
    trace: dict[str, Any]
    checks: list[CheckResult] = field(default_factory=list)

    @property
    def passed(self) -> bool:
        return all(c.passed for c in self.checks)

    @property
    def outcome(self) -> str:
        return next((c.name for c in self.checks if not c.passed), "pass")


def score_trace(trace: dict[str, Any]) -> Scored:
    """Score one production trace with the reference-free checks, in CHECKS order, collecting every failure."""
    looked: dict[str, FlightRecord | None] = {}
    confirmed, trajectory, assertions = [], [], []
    seen: set[tuple[str, ...]] = set()
    for call in trace["calls"]:
        name, args, result = call["name"], call.get("args", {}), call.get("result", {})
        f = flight_key(args.get("flight_number", ""))
        if name == "get_flight_status":
            looked[f] = _record(result)
            continue
        if name not in WRITE_TOOLS:
            continue
        if f not in looked:
            trajectory.append(f"write before verifying: {name} {f}")
        tgt = write_target(name, args)
        if tgt in seen:
            trajectory.append(f"repeated write: {name}")
        seen.add(tgt)
        if name != "notify_passengers" or result.get("status") != "sent":
            continue
        rec, msg, reason = looked.get(f), str(args.get("message", "")), args.get("reason")
        if rec is None:
            confirmed.append(f"not confirmed: {f} {reason}: no lookup result")
            continue
        want = {"delay": "DELAYED", "cancellation": "CANCELLED"}.get(reason)
        if want and rec.status != want:
            confirmed.append(f"not confirmed: {f} {reason}, but the system says {rec.status}")
        elif reason == "delay" and rec.estimated_departure not in msg:
            confirmed.append(f"not confirmed: {f} delay time, the system says {rec.estimated_departure}")
        elif reason == "gate_change" and (not rec.gate or not re.search(rf"\b{re.escape(rec.gate)}\b", msg)):
            confirmed.append(f"not confirmed: {f} gate change, the system says gate {rec.gate}")
        assertions += [f"{f}: {x}" for x in message_assertions(msg, rec)]
    return Scored(trace, [CheckResult("confirmed", confirmed), CheckResult("trajectory", trajectory),
                          CheckResult("assertions", assertions)])


# ---------- drift ----------

def psi(expected: dict[str, int], actual: dict[str, int], eps: float = 1e-4) -> float:
    """Lecture 11.5: the population stability index between two count distributions over the same bins.

    Bins are the union of both dicts' keys (a key missing from one dict has count 0 there). Turn each dict into
    shares of its own total (raise ValueError if either total is 0). Replace any share of exactly 0 with eps,
    without renormalising, so an empty bin doesn't divide by zero. Then
    PSI = sum over bins of (a - e) * ln(a / e), with e the expected share and a the actual share. Return it as a
    float (0 when the distributions are identical; it is symmetric in the two inputs).
    Rule of thumb, widely used and never derived (it dates from credit scoring): below 0.1 little change,
    0.1 to 0.25 moderate, above 0.25 a large shift. Its spread depends on the sample size and the number of bins,
    so read it next to the counts, and pair it with a test that knows about n.
    """
    te, ta = sum(expected.values()), sum(actual.values())
    if te == 0 or ta == 0:
        raise ValueError("both distributions need at least one count")
    total = 0.0
    for b in sorted(set(expected) | set(actual)):
        e = expected.get(b, 0) / te or eps
        a = actual.get(b, 0) / ta or eps
        total += (a - e) * math.log(a / e)
    return total


PSI_LITTLE, PSI_LARGE = 0.1, 0.25     # the rule-of-thumb bands (credit scoring, Lewis 1994): a convention


def new_bins(expected: dict[str, int], actual: dict[str, int]) -> list[str]:
    """Bins with traffic now and none in the reference. PSI is undefined there (infinite without an epsilon, and the
    epsilon then decides the number), so report them as what they are: a kind of input never seen before."""
    return [b for b in sorted(actual) if actual[b] and not expected.get(b)]


def psi_band(x: float) -> str:
    return "little change" if x < PSI_LITTLE else "moderate shift" if x < PSI_LARGE else "large shift"


FEED = re.compile(r"^OPSFEED/\d")
SHORTHAND = re.compile(r"\b(?:ETD|STD|ETA|CNX|pax|acft|o/o)\b|\b\d{4}L\b", re.I)


def notice_format(notice: str) -> str:
    """The shape of a notice, for input drift: "feed" (the OPSFEED/2 lines), "shorthand" (ops codes), or "prose"."""
    if FEED.match(notice.strip()):
        return "feed"
    return "shorthand" if SHORTHAND.search(notice) else "prose"


def outcome_counts(scored: list[Scored]) -> dict[str, int]:
    c = Counter(s.outcome for s in scored)
    return {k: c.get(k, 0) for k in CLASSES}


def check_failures(scored: list[Scored]) -> dict[str, int]:
    return {name: sum(not next(c for c in s.checks if c.name == name).passed for s in scored) for name in CHECKS}


# ---------- the human review queue ----------

def review_queue(scored: list[Scored], per_day: int = 12, rate_pass: float = 0.25,
                 salt: str = SALT) -> dict[str, list[dict[str, Any]]]:
    """One day's queue for people: every sampled trace a check failed, then a hashed share of the passing ones
    (what code missed is only found by reading passes), capped at `per_day`. Each item says why it is there.
    Reviewers' verdicts become labels: new held-out cases (11.4) and judge calibration labels (Section 10)."""
    days: dict[str, list[dict[str, Any]]] = {}
    for s in sorted(scored, key=lambda s: s.trace["trace_id"]):
        day = s.trace["day"]
        if not s.passed:
            why = f"check failed: {s.outcome}"
        elif in_sample(s.trace["trace_id"], rate_pass, salt + ":review"):
            why = "random pass"
        else:
            continue
        days.setdefault(day, []).append({"trace_id": s.trace["trace_id"], "why": why,
                                         "failures": [f for c in s.checks for f in c.failures]})
    return {d: sorted(q, key=lambda x: x["why"] == "random pass")[:per_day] for d, q in sorted(days.items())}
